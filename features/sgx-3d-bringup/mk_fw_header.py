#!/usr/bin/env python3
# mk_fw_header.py - SGX535 EMGD microkernel firmware packer for the Poulsbo
# gma500 3D bring-up.
#
# Two jobs:
#   (1) validate the extracted .bin blobs against the byte-exact sizes recovered
#       from libemgdsrv_init.so (recon: fw-tables), and
#   (2) emit an optional self-contained C header (sgx_fw_blob.h) with the blobs
#       embedded as aui32[] arrays, for builds that do NOT want request_firmware.
#
# The default / recommended path is request_firmware() (see sgx_3d.c); the .bin
# files are copied verbatim into /lib/firmware/sgx535/. This tool's PRIMARY value
# is the validation + the static offset/size tables it prints, which must match
# sgx_fw.h. Every table value here is transcribed from the recon dump of
# libemgdsrv_init.so.1.5.15.3226 (.data 0x1d538..0x1d5a8) and is marked GUESSED
# only where the recon itself flagged runtime/.bss values.
#
# Usage:
#   ./mk_fw_header.py --fwdir /Projects/Poulsbo/firmware/sgx535-emgd-1.18 \
#                     [--emit-blob-header sgx_fw_blob.h]
#
import argparse
import hashlib
import os
import sys

# --- Byte-exact sizes recovered from the .so (.data scalars). Must match file. ---
PROGRAMS = {
    # name             file                       size    align  request_firmware name
    "main": ("pbuKernelProgram.bin",   22552, 0x8000, "sgx535/pbuKernelProgram.bin"),
    "ta":   ("pbuKernelTAProgram.bin", 21672, 0x8000, "sgx535/pbuKernelTAProgram.bin"),
    "3d":   ("pbuKernel3DProgram.bin", 25240, 0x8000, "sgx535/pbuKernel3DProgram.bin"),
}

# --- Service byte-offsets into the MAIN flat blob (recon: all CONFIRMED, static). ---
MAIN_OFFSETS = {
    "EVENTHANDLER":        0x0010,  # entry the HW runs on EVENT_KICK (load-bearing)
    "HOSTKICKPOWER":       0x1038,
    "HOSTKICK2D":          0x10f8,
    "HOSTKICKTRANSFER":    0x11d0,
    "HOSTKICKTA":          0x12a0,  # first render kick target
    "HOSTKICKCLEANUP":     0x1388,
    "HOSTKICKPROCESS_QUEUES": 0x1470,
    "HOSTKICKGETMISCINFO": 0x1520,
    "INITUKERNELPRIMARY1": 0x1700,
    "INITUKERNELSECONDARY": 0x1780,
    "INITUKERNELPRIMARY2": 0x1790,
}
# Offsets internal to the TA / 3D blobs (relative to their OWN devVAddr).
TA_HANDLER = 0x0680
THREED_HANDLER = 0x0900
# NOTE (recon gotcha): TA_TAEVENTHANDLER / 3D_THREEDEVENTHANDLER live in .bss and
# are runtime-computed. They are NOT hardcodable and are intentionally absent here.


def packed_use_addr(buf_dev_vaddr, offset, code_heap_base):
    """USE exec-address packing recovered from SGXInit disasm (0x1e65-0x1eec).
    delta = byte offset of the routine within the USE code segment."""
    delta = (buf_dev_vaddr + offset - code_heap_base) & 0xffffffff
    low19 = delta & 0x7ffff
    high = delta >> 19
    word = (((high + 0xf) & 0xf)
            | 0x200000
            | ((low19 >> 15) << 4)
            | ((low19 << 4) & 0x7ff00))
    return word & 0xffffffff


def validate(fwdir):
    ok = True
    for name, (fn, size, _align, _rf) in PROGRAMS.items():
        path = os.path.join(fwdir, fn)
        if not os.path.exists(path):
            print("MISSING: %s" % path); ok = False; continue
        data = open(path, "rb").read()
        tag = "OK" if len(data) == size else "SIZE-MISMATCH"
        if len(data) != size:
            ok = False
        print("  %-5s %-24s %6d bytes (expect %6d) sha256=%s [%s]" %
              (name, fn, len(data), size, hashlib.sha256(data).hexdigest()[:16], tag))
    return ok


def emit_blob_header(fwdir, out):
    lines = []
    lines.append("/* AUTO-GENERATED by mk_fw_header.py - do not edit. */")
    lines.append("/* Embedded SGX535 EMGD 1.18 microkernel blobs (fallback to request_firmware). */")
    lines.append("#ifndef _SGX_FW_BLOB_H_")
    lines.append("#define _SGX_FW_BLOB_H_")
    lines.append("")
    for name, (fn, size, _align, _rf) in PROGRAMS.items():
        data = open(os.path.join(fwdir, fn), "rb").read()
        # pad to multiple of 4 for u32 array
        if len(data) % 4:
            data = data + b"\x00" * (4 - (len(data) % 4))
        words = [int.from_bytes(data[i:i+4], "little") for i in range(0, len(data), 4)]
        sym = "sgx_fw_%s" % name
        lines.append("static const u32 %s[] = {" % sym)
        for i in range(0, len(words), 8):
            chunk = words[i:i+8]
            lines.append("\t" + " ".join("0x%08x," % w for w in chunk))
        lines.append("};")
        lines.append("static const u32 %s_size = %d; /* real byte length, pre-pad */" % (sym, size))
        lines.append("")
    lines.append("#endif /* _SGX_FW_BLOB_H_ */")
    open(out, "w").write("\n".join(lines) + "\n")
    print("wrote %s" % out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--fwdir", default="/Projects/Poulsbo/firmware/sgx535-emgd-1.18")
    ap.add_argument("--emit-blob-header", metavar="OUT")
    ap.add_argument("--selftest-pack", action="store_true",
                    help="run the address-packing selftest (delta==offset case)")
    args = ap.parse_args()

    print("== validating blobs in %s ==" % args.fwdir)
    ok = validate(args.fwdir)

    if args.selftest_pack:
        # delta==offset simplification: code placed AT code-heap base.
        base = 0xF8000000
        print("== packed USE addrs (code at heap base, delta==offset) ==")
        for k, off in MAIN_OFFSETS.items():
            print("  %-22s off=0x%05x -> 0x%08x" % (k, off, packed_use_addr(base, off, base)))

    if args.emit_blob_header:
        if not ok:
            print("refusing to emit header: validation failed"); sys.exit(1)
        emit_blob_header(args.fwdir, args.emit_blob_header)

    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
